"""Recording plan built from the gold set:  python3 build_sheets.py
Writes docs/recording-sheets.md (one section per speaker, readable on a phone) and
app/src/main/assets/eval/manifest.jsonl (one planned row per clip; fill device, mic,
captured_at and duration_s while recording, and type `reference` for prompted clips by ear).
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
GOLD = REPO / "app/src/main/assets/eval/gold_v1.jsonl"
SHEETS = REPO / "docs/recording-sheets.md"
MANIFEST = REPO / "app/src/main/assets/eval/manifest.jsonl"

# Per speaker: deck calm + deck stressed, two scripted, three prompted single-turn, one prompted multi-turn.
SCRIPTED = {"S1": ["g02", "g11"], "S2": ["g04", "g12"], "S3": ["g16", "g17"], "S4": ["g21", "g24"], "S5": ["g27", "g32"]}
PROMPTED = {"S1": ["g05", "g13", "g22"], "S2": ["g06", "g14", "g26"], "S3": ["g07", "g15", "g28"],
            "S4": ["g08", "g18", "g29"], "S5": ["g10", "g20", "g31"]}
MULTI = {"S1": "g34", "S2": "g35", "S3": "g37", "S4": "g38", "S5": "g39"}
# Indic extras (prompted from the same cards; assign to fluent speakers on the day).
INDIC = [("hi", g) for g in ("g02", "g07", "g08", "g10", "g12", "g15")] + [("te", g) for g in ("g03", "g06", "g13", "g17")]

CONDITION_NOTE = {
    "clean": "normal voice, quiet room",
    "stressed": "same words, but fast and urgent, as if it is happening right now",
    "noise": "fan or AC on full, same distance",
    "alarm": "play a fire-alarm sound from a phone about 1 m away while you speak",
    "correction": "change one detail mid-sentence (\"...at ten, no wait, half past ten\")",
}


def load_gold() -> dict:
    return {i["id"]: i for i in (json.loads(l) for l in GOLD.read_text(encoding="utf-8").splitlines() if l.strip())}


def card(item: dict) -> list[str]:
    """Keywords for a prompted clip, from the gold values (never the full sentence)."""
    g, out = item["gold"], []
    label = {"incident_type": "What", "location": "Where", "date_time": "When", "equipment_asset": "Equipment",
             "persons_involved": "Involved", "witnesses": "Saw it", "immediate_actions": "Done so far", "severity": "Severity"}
    for f, name in label.items():
        slot = g[f]
        if slot["status"] in ("REPORTED", "SUGGESTED"):
            val = slot.get("text") if f == "date_time" else slot["value"]
            val = ", ".join(val) if isinstance(val, list) else str(val).replace("_", " ")
            out.append(f"{name}: {val}" + (" (say it unsure)" if slot["status"] == "SUGGESTED" else ""))
        elif slot["status"] == "EXPLICIT_NONE":
            out.append(f"{name}: say nobody")
    return out


def plan_clips() -> list[dict]:
    gold = load_gold()
    clips: list[dict] = []

    def add(speaker, gold_id, mode, condition, language="en", clip_id=None):
        item = gold[gold_id]
        clips.append({
            "clip_id": clip_id or f"{speaker}_{sum(c['speaker'] == speaker for c in clips) + 1:02d}",
            "wav": "", "reference": " ".join(item["turns"]) if mode == "scripted" else "",
            "gold_id": gold_id, "device": "", "mic": "", "speaker": speaker, "mode": mode, "language": language,
            "condition": condition, "captured_at": "", "duration_s": None,
            "script": item["turns"] if mode == "scripted" else [], "card": card(item) if mode == "prompted" else [],
            "followups": item["turns"][1:] if mode == "prompted" and len(item["turns"]) > 1 else [],
            "tags": item["tags"],
        })

    for s in ("S1", "S2", "S3", "S4", "S5"):
        add(s, "g01", "scripted", "clean")
        add(s, "g01", "scripted", "stressed")
        add(s, SCRIPTED[s][0], "scripted", "clean")
        add(s, SCRIPTED[s][1], "scripted", "noise")
        add(s, PROMPTED[s][0], "prompted", "clean")
        add(s, PROMPTED[s][1], "prompted", "alarm")
        add(s, PROMPTED[s][2], "prompted", "correction")
        add(s, MULTI[s], "prompted", "clean")
    for n, (lang, gid) in enumerate(INDIC, start=1):
        add("S?", gid, "prompted", "clean", language=lang, clip_id=f"I{n:02d}_{lang}")
    for c in clips:
        c["wav"] = f"audio/{c['clip_id']}.wav"
    return clips


def render(clips: list[dict]) -> str:
    out = ["# Recording sheets", "",
           "Generated by `tools/laptop_eval/build_sheets.py` from the gold set. Speakers are S1 to S5 (no names in any file).",
           "", "**Setup (same for every clip):** the demo mic and distance, quiet room unless the condition says otherwise. "
           "Save as `<clip id>.wav` (16 kHz mono; convert later with `ffmpeg -i in.m4a -ac 1 -ar 16000 out.wav`). "
           "Re-take only for clipping or a false start, never for accent or hesitation.", "",
           "**Scripted:** read the text exactly. **Prompted:** look at the card for a few seconds, put it away, and report it "
           "in your own words as if calling it in. If the card has follow-ups, the listener asks \"anything else?\" "
           "and you answer with them.", ""]
    for speaker in ("S1", "S2", "S3", "S4", "S5", "S?"):
        mine = [c for c in clips if c["speaker"] == speaker]
        out += [f"## {speaker if speaker != 'S?' else 'Hindi / Telugu extras (fluent speakers)'}", ""]
        for c in mine:
            out.append(f"### {c['clip_id']} · {c['mode']} · {c['condition']} · {c['language']}")
            out.append(f"*{CONDITION_NOTE[c['condition']]}*")
            out.append("")
            if c["script"]:
                out += [f"> {t}" for t in c["script"]]
            else:
                if c["language"] != "en":
                    out.append(f"Speak in {'Hindi or Hinglish' if c['language'] == 'hi' else 'Telugu'}.")
                out += [f"- {k}" for k in c["card"]]
                if c["followups"]:
                    out.append(f"- Follow-up answers (record as `{c['clip_id']}_b.wav` after the listener asks): {' / '.join(c['followups'])}")
            out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    clips = plan_clips()
    SHEETS.write_text(render(clips), encoding="utf-8")
    keep = ("clip_id", "wav", "reference", "gold_id", "device", "mic", "speaker", "mode", "language", "condition",
            "captured_at", "duration_s")
    MANIFEST.write_text("".join(json.dumps({k: c[k] for k in keep}, ensure_ascii=False) + "\n" for c in clips),
                        encoding="utf-8")
    print(f"{len(clips)} clips -> {SHEETS.relative_to(REPO)}, {MANIFEST.relative_to(REPO)}")
